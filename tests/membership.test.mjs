import assert from "node:assert/strict";
import test from "node:test";
import {DatabaseSync} from "node:sqlite";
import {readFileSync} from "node:fs";
import {build} from "esbuild";
const bundle=await build({entryPoints:["lib/membership-server.ts"],bundle:true,platform:"node",format:"esm",write:false});
const {membershipRequest}=await import("data:text/javascript;base64,"+Buffer.from(bundle.outputFiles[0].text).toString("base64"));
test("receipt totals, account binding, thresholds and confirmed role delivery",async()=>{
  const sql=new DatabaseSync(":memory:");
  sql.exec(readFileSync("drizzle/0005_membership_passport.sql","utf8"));
  const db={prepare(query){return {bind(...args){
    const statement=sql.prepare(query);
    return {first:async key=>{const row=statement.get(...args);return key?row?.[key]:row;},all:async()=>({results:statement.all(...args)}),run:async()=>({meta:{changes:statement.run(...args).changes}})};
  }}}};
  const origin="https://shop.test",id="10000000000000001";
  const env={DISCORD_CLIENT_ID:id,DISCORD_CLIENT_SECRET:"sample",DISCORD_GUILD_ID:id,DISCORD_BOT_TOKEN:"test",DISCORD_RICH_CLIENT_ROLE_ID:"12345678910000001",DISCORD_LEVIATHAN_ROLE_ID:"12345678910000002"};
  let roleStatus=403,calls=0;
  let discordRoles=[];
  const provider=async(url,init)=>{
    if(url.endsWith("/members/"+id))return Response.json({roles:discordRoles});
    if(url.endsWith("/oauth2/token"))return Response.json({access_token:"test"});
    if(url.endsWith("/users/@me"))return Response.json({id,username:"test-user"});
    assert.equal(init.method,"PUT");calls++;return new Response(null,{status:roleStatus});
  };
  function req(action,owner,body,query="",requestOrigin=origin) {
    const request=new Request(origin+"/api/membership/"+action+query,{method:body?"POST":"GET",headers:{origin:requestOrigin,...owner&&{"oai-authenticated-user-id":owner}},body:body?JSON.stringify(body):undefined});
    return membershipRequest(request,action,db,env,async()=>owner==="staff",provider);
  }
  assert.equal((await (await req("status",null)).json()).account,null);
  const {account:{code}}=await (await req("status","buyer")).json();
  const sale=(receipt,amount)=>({receipt,amount,code});
  const claim=(tier,kind)=>req("claim","buyer",{tier,kind});
  assert.equal((await req("sale","buyer",sale("x",12000))).status,403);
  assert.equal((await req("sale","staff",sale("x",10000),"","https://other.test")).status,403);
  await req("sale","staff",sale("a",9999));
  assert.equal((await claim(10000,"stamp")).status,403);
  await req("sale","staff",sale("b",1));
  assert.equal((await (await req("sale","staff",sale("b",1))).json()).total,10000);
  assert.equal((await req("sale","staff",sale("b",2))).status,409);
  assert.equal((await claim(10000,"stamp")).status,200);
  assert.equal((await claim(10000,"stamp")).status,200);
  assert.equal((await claim(50000,"stamp")).status,403);
  assert.equal((await claim(10000,"role")).status,409);
  const connect=await req("connect","buyer");
  const state=new URL(connect.headers.get("location")).searchParams.get("state");
  assert.equal((await req("callback","other",null,"?code=abc&state="+state)).headers.get("location"),"/membership?link=expired");
  const callback=()=>req("callback","buyer",null,"?code=abc&state="+state);
  assert.equal((await callback()).headers.get("location"),"/membership?link=linked");
  assert.equal((await callback()).headers.get("location"),"/membership?link=expired");
  assert.equal((await claim(10000,"role")).status,503);
  assert.equal((await (await req("status","buyer")).json()).account.claims.length,1);
  roleStatus=204;
  assert.equal((await claim(10000,"role")).status,200);
  assert.equal((await claim(10000,"role")).status,200);
  assert.equal(calls,2);
  await req("sale","staff",sale("c",39999));
  assert.equal((await claim(50000,"role")).status,403);
  await req("sale","staff",sale("d",1));
  assert.equal((await claim(50000,"stamp")).status,200);
  assert.equal((await claim(50000,"role")).status,200);
  assert.equal((await (await req("status","buyer")).json()).account.claims.length,4);
  assert.equal((await (await req("status","other")).json()).account.total,0);
  const feedback=async(owner)=>(await (await req("feedback",owner)).json()).role;
  assert.equal(await feedback(null),null);
  assert.equal(await feedback("buyer"),null);
  discordRoles=[env.DISCORD_RICH_CLIENT_ROLE_ID];
  assert.equal(await feedback("buyer"),"rich client");
  discordRoles.push(env.DISCORD_LEVIATHAN_ROLE_ID);
  assert.equal(await feedback("buyer"),"leviathan");
  assert.equal(await feedback("other"),null);
  discordRoles=[];
  assert.equal(await feedback("buyer"),null);
  sql.close();
});
